#!/usr/bin/env python3
"""Turn the Ghidra export (ExportAnalysis.java) into docs/ghidra.md and a leaf-function list.

    report.py build/ghidra/age2_x1.json --out docs/ghidra.md --leaves build/ghidra/leaves.json
"""
from __future__ import annotations

import argparse
import collections
import json
import re
from pathlib import Path


def h(x: int) -> str:
    return f"0x{x:08x}"


def md_table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def classify_icall(op: str, iat_lo: int, iat_hi: int) -> str:
    o = op.replace(" ", "").lower()
    m = re.fullmatch(r"(?:dword ptr)?\[0x([0-9a-f]+)\]", o.replace("dwordptr", ""))
    if m:
        a = int(m.group(1), 16)
        return "import (call [IAT])" if iat_lo <= a < iat_hi else "global function pointer"
    if re.fullmatch(r"e[a-ds][xip]|e[sd]i|ebp|esp", o):
        return "register"
    if "[" in o:
        if re.search(r"\*[248]", o):
            return "indexed table [reg*4+base]"
        return "memory [reg+disp] (vtable / struct fn ptr)"
    return "other"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("json", type=Path)
    ap.add_argument("--out", type=Path, default=Path("docs/ghidra.md"))
    ap.add_argument("--leaves", type=Path)
    a = ap.parse_args()
    d = json.loads(a.json.read_text())
    blocks = d["blocks"]
    rdata = next((b for b in blocks if b["name"] == ".rdata"), None)
    # IAT sits at the start of .rdata in MSVC6 images; imports are the only absolute calls into it.
    iat_lo = int(rdata["start"], 16) if rdata else 0
    iat_hi = iat_lo + 0x1000

    F = d["functions"]
    internal = [f for f in F if not f["external"]]
    thunks = [f for f in internal if f["thunk"]]
    real = [f for f in internal if not f["thunk"]]
    sizes = sorted(f["size"] for f in real)
    ninsn = sum(f["ninsn"] for f in real)

    def pct(p):
        return sizes[min(len(sizes) - 1, int(p / 100 * len(sizes)))]

    exec_blocks = [b for b in blocks if b["exec"]]
    exec_bytes = sum(int(b["end"], 16) - int(b["start"], 16) + 1 for b in exec_blocks)
    in_funcs = sum(f["size"] for f in internal)
    undef = d["undefined_exec"]
    undef_bytes = sum(n for _, n in undef)
    dic = d["data_in_code"]
    dic_types = collections.Counter()
    dic_bytes = collections.Counter()
    for x in dic:
        t = re.sub(r"\[\d+\]$", "[]", x["type"])
        dic_types[t] += 1
        dic_bytes[t] += x["len"]

    icall_kinds = collections.Counter()
    for f in real:
        for c in f["icalls"]:
            icall_kinds[classify_icall(c["op"], iat_lo, iat_hi)] += 1
    ijmp_total = sum(len(f["ijmps"]) for f in real)
    ijmp_resolved = sum(1 for f in real for j in f["ijmps"] if j["refs"])
    ijmp_targets = sum(len(j["refs"]) for f in real for j in f["ijmps"])
    ijmp_unres = [(f, j) for f in real for j in f["ijmps"] if not j["refs"]]
    ijmp_import = sum(1 for f, j in ijmp_unres if classify_icall(j["op"], iat_lo, iat_hi).startswith("import"))

    buckets = [(0, 16), (16, 64), (64, 256), (256, 1024), (1024, 4096), (4096, 16384), (16384, 1 << 30)]
    rows = []
    for lo, hi in buckets:
        n = sum(1 for s in sizes if lo <= s < hi)
        b = sum(s for s in sizes if lo <= s < hi)
        rows.append([f"{lo}-{hi - 1 if hi < 1 << 30 else '...'}", n, f"{n / len(sizes) * 100:.1f}%", f"{b:,}"])

    fpu_f = [f for f in real if f["fpu"]]
    mmx_f = [f for f in real if f["mmx"]]
    sse_f = [f for f in real if f["sse"]]
    seh_f = [f for f in real if f["seh"]]
    noret = [f for f in real if f["no_return"]]
    noret_names = sorted(set(f["name"] for f in noret))
    cc = collections.Counter(f["cc"] for f in real)
    leaves = [f for f in real if not f["calls"] and not f["icalls"] and not f["ijmps"] and f["rets"] > 0]
    by_block = collections.Counter()
    for f in real:
        ea = int(f["entry"], 16)
        for b in blocks:
            if int(b["start"], 16) <= ea <= int(b["end"], 16):
                by_block[b["name"]] += 1
    biggest = sorted(real, key=lambda f: -f["size"])[:10]
    mnem_note = ""

    L = []
    w = L.append
    w(f"# Ghidra headless analysis: `{d['program']}`\n")
    w("_Generated by `make ghidra` (tools/ghidra/run.sh + ExportAnalysis.java + report.py). Ghidra auto-analysis with default analysers._\n")
    w("## Functions\n")
    w(md_table(["Metric", "Value"], [
        ["Functions (internal)", f"{len(internal):,}"],
        ["of which thunks (`jmp [IAT]` stubs)", len(thunks)],
        ["Real functions", f"{len(real):,}"],
        ["Instructions in real functions", f"{ninsn:,}"],
        ["Functions per section", ", ".join(f"`{k}` {v}" for k, v in sorted(by_block.items()))],
        ["Size median / p90 / p99 / max (bytes)", f"{pct(50)} / {pct(90)} / {pct(99)} / {sizes[-1]:,}"],
        ["Calling conventions (Ghidra's guess)", ", ".join(f"{k} {v}" for k, v in cc.most_common())],
        ["No-return functions", f"{len(noret)} ({', '.join(noret_names[:8])}{' ...' if len(noret_names) > 8 else ''})"],
        ["Leaf functions (no calls, no indirect jumps, has ret)", f"{len(leaves):,}"],
        ["Code pointers stored in data sections (4-byte aligned words that equal a function entry)", f"{d['code_ptrs_in_data']:,}"],
    ]) + "\n")
    w("### Size distribution\n")
    w(md_table(["Size (bytes)", "Functions", "Share", "Total bytes"], rows) + "\n")
    w("### Largest functions\n")
    w(md_table(["Entry", "Name", "Bytes", "Instructions", "Indirect jumps"],
               [[f["entry"], f["name"], f"{f['size']:,}", f["ninsn"], len(f["ijmps"])] for f in biggest]) + "\n")

    w("## Coverage of executable sections\n")
    w(md_table(["Metric", "Bytes", "Share"], [
        ["Executable section bytes", f"{exec_bytes:,}", "100%"],
        ["Inside function bodies", f"{in_funcs:,}", f"{in_funcs / exec_bytes * 100:.1f}%"],
        ["Defined data inside code sections", f"{sum(x['len'] for x in dic):,}", f"{sum(x['len'] for x in dic) / exec_bytes * 100:.2f}%"],
        ["Undefined bytes (neither code nor data)", f"{undef_bytes:,}", f"{undef_bytes / exec_bytes * 100:.2f}%"],
    ]) + "\n")
    # Whatever is neither a function body, defined data nor undefined is disassembled code that
    # belongs to no function: unreached, or only reachable through pointers Ghidra did not follow.
    covered = []
    for f in internal:
        for lo, hi in f["ranges"]:
            covered.append((int(lo, 16), int(hi, 16) + 1))
    covered += [(int(x["at"], 16), int(x["at"], 16) + x["len"]) for x in dic]
    covered += [(int(s, 16), int(s, 16) + n) for s, n in undef]
    covered.sort()
    orphans = []
    for b in exec_blocks:
        cur, end = int(b["start"], 16), int(b["end"], 16) + 1
        for lo, hi in covered:
            if hi <= cur or lo >= end:
                continue
            if lo > cur:
                orphans.append((cur, lo - cur))
            cur = max(cur, hi)
        if cur < end:
            orphans.append((cur, end - cur))
    orphan_bytes = sum(n for _, n in orphans)
    w(f"**Code outside any function:** {orphan_bytes:,} bytes ({orphan_bytes / exec_bytes * 100:.1f}%) in {len(orphans):,} runs. "
      "Ghidra disassembled these bytes but put them in no function. They are either dead code or code reached only through pointers it did not follow "
      "(callbacks, vtables in `.rdata`, the `this_cod` library). The lifter must cover them, for example by seeding function starts from the code pointers in data. "
      "Largest runs: " + ", ".join(f"{h(s)} ({n:,} B)" for s, n in sorted(orphans, key=lambda x: -x[1])[:8]) + ".\n")
    big_gaps = sorted(undef, key=lambda x: -x[1])[:8]
    w(f"Undefined runs: {len(undef):,}. Most are alignment padding (`int3`/`nop` between functions). Largest: " +
      ", ".join(f"{s} ({n} B)" for s, n in big_gaps) + ".\n")
    w("Data embedded in code sections, by type:\n")
    w(md_table(["Type", "Items", "Bytes"], [[f"`{t}`", n, dic_bytes[t]] for t, n in dic_types.most_common(12)]) + "\n")

    w("## Indirect control flow\n")
    tot_ic = sum(icall_kinds.values())
    w(f"**Indirect calls: {tot_ic:,}**\n")
    w(md_table(["Kind", "Count", "Share"], [[k, f"{v:,}", f"{v / tot_ic * 100:.1f}%"] for k, v in icall_kinds.most_common()]) + "\n")
    w("Calls through the IAT are resolved at lift time and become direct calls into the shim. Vtable and struct function-pointer calls need a runtime dispatch from guest address to lifted function. "
      "The candidate set is every function entry plus the code pointers stored in data.\n")
    w(f"**Indirect jumps: {ijmp_total:,}**. Ghidra recovered a switch table for {ijmp_resolved:,} of them ({ijmp_targets:,} case targets in total). "
      f"{len(ijmp_unres)} remain without targets, {ijmp_import} of which are `jmp [IAT]` tail calls into imports.\n")
    if ijmp_unres:
        rows = [[f["entry"], j["at"], f"`{j['op']}`"] for f, j in ijmp_unres if not classify_icall(j["op"], iat_lo, iat_hi).startswith("import")][:20]
        if rows:
            w("Unresolved computed jumps (first 20):\n")
            w(md_table(["Function", "At", "Operand"], rows) + "\n")

    w("## Lift hazards\n")
    wx = d["writes_to_exec"]
    w(f"- **Self-modifying code:** Ghidra found {len(wx)} direct writes into executable sections. "
      "Indirect writes through computed pointers cannot be ruled out statically. The differential and runtime harnesses should check `.text` for integrity.")
    w(f"- **Data in code:** {len(dic):,} items ({sum(x['len'] for x in dic):,} bytes), mostly switch tables. MSVC6 places switch jump tables and byte-index tables right after the function. "
      "The lifter has to take them from Ghidra's analysis; a linear sweep would decode them as instructions.")
    w(f"- **Computed jumps:** {ijmp_total:,} jumps, {ijmp_total - len(ijmp_unres)} with recovered tables (see above).")
    w(f"- **x87 FPU:** {len(fpu_f):,} functions ({len(fpu_f) / len(real) * 100:.1f}%) use x87 instructions. Simulation code using floats is a determinism risk: "
      "lifted code must reproduce x87 results (80-bit intermediates, the precision-control word MSVC sets, `fistp` rounding) bit for bit, or multiplayer and recorded-game replays desync.")
    w(f"- **MMX:** {len(mmx_f)} functions. **SSE:** {len(sse_f)} functions." +
      (f" MMX users: {', '.join(f['entry'] for f in mmx_f[:12])}{' ...' if len(mmx_f) > 12 else ''}." if mmx_f else ""))
    w(f"- **SEH:** {len(seh_f):,} functions install an `fs:[0]` handler, either `_except_handler3` (C `__try`) or C++ EH through `__CxxFrameHandler`. "
      "Unwinding has to be modelled: either setjmp/longjmp-style unwinding in lifted code, or proof that the exceptions never fire in practice.")
    tc = [f for f in real if f["entry"] >= "0x00628000" and f["entry"] < "0x00634000"]
    w(f"- **`this_cod` section:** {len(tc)} functions, {sum(f['size'] for f in tc):,} bytes, {sum(f['fpu'] for f in tc)} x87 and {sum(f['mmx'] for f in tc)} MMX instructions. "
      "A named code section like this comes from `#pragma code_seg` or a third-party library linked as its own section. Its RW companions are `this_dat`/`inf32dat`.")
    w("")
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text("\n".join(L) + "\n")
    if a.leaves:
        a.leaves.parent.mkdir(parents=True, exist_ok=True)
        a.leaves.write_text(json.dumps([{k: f[k] for k in ("entry", "name", "size", "ninsn", "ranges", "fpu", "mmx", "sse", "seh", "rets", "stack_purge", "cc")} for f in leaves], indent=1))
    print(f"ghidra report: {len(real)} functions, {len(leaves)} leaves -> {a.out}")


if __name__ == "__main__":
    main()
